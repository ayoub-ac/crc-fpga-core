"""Generate random CRC test vectors for the C++ harness.

Output: a C++ header (random_vectors.h) defining a flat byte arena and
five tables of {offset, length, expected_crc} tuples - one per standard.
The harness in sim_main.cpp drives each DUT instance through 100 random
inputs and compares the finalised CRC against `crcmod` reference values.

Run: `python3 tb/gen_random.py > tb/random_vectors.h`
(invoked by `make regen_vectors`). Deterministic given the seed.
"""

import random
import sys

import crcmod.predefined as cp


STANDARDS = [
    # (display, struct_field, crcmod_name, width_bits)
    ("CRC-32 Ethernet",      "eth",    "crc-32",         32),
    ("CRC-32C iSCSI",        "iscsi",  "crc-32c",        32),
    ("CRC-16-CCITT (X.25)",  "x25",    "x-25",           16),
    ("CRC-16-IBM (Modbus)",  "modbus", "modbus",         16),
    ("CRC-8 (CAN)",          "can",    "crc-8",          8),
]


def main() -> int:
    random.seed(0xC2C0FFEE)

    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later OR Commercial\n")
    out.write("// AUTO-GENERATED by tb/gen_random.py.\n"
              "// Do not edit by hand; regenerate with `make regen_vectors`.\n")
    out.write("#pragma once\n")
    out.write("#include <cstdint>\n")
    out.write("#include <cstddef>\n\n")

    out.write("struct CrcVec {\n")
    out.write("    size_t   off;\n")
    out.write("    size_t   len;\n")
    out.write("    uint32_t expected;\n")
    out.write("};\n\n")

    arena = bytearray()
    tables: dict[str, list[tuple[int, int, int]]] = {f: [] for _, f, _, _ in STANDARDS}

    # Length schedule covers edge cases: empty, 1 byte, alignments around 4
    # (parallel-word boundary), powers of 2, and random sizes up to 1 KB.
    length_schedule = (
        [0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100,
         128, 200, 255, 256, 257, 511, 512, 1024]
        + [random.randint(0, 1024) for _ in range(73)]
    )
    length_schedule = length_schedule[:100]
    while len(length_schedule) < 100:
        length_schedule.append(random.randint(0, 1024))

    # All five standards see the SAME 100 length schedule and the SAME 100
    # input buffers. Each gets its own expected-CRC list.
    inputs: list[bytes] = []
    for length in length_schedule:
        inputs.append(bytes(random.randint(0, 255) for _ in range(length)))

    for inp in inputs:
        offs = []
        # Each input lands in the arena once and is shared across all five
        # standards' tables. The empty input still gets a (0,0) entry.
        offs.append(len(arena))
        arena.extend(inp)
        for _disp, field, name, width in STANDARDS:
            ref = cp.mkCrcFun(name)
            crc = ref(inp)
            tables[field].append((offs[0], len(inp), crc))

    arena.append(0)

    out.write("static const uint8_t kCrcArena[] = {\n")
    for i in range(0, len(arena), 16):
        chunk = arena[i:i + 16]
        out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n\n")

    for _disp, field, _name, _w in STANDARDS:
        out.write(f"static const CrcVec kVec_{field}[] = {{\n")
        for off, ln, crc in tables[field]:
            out.write(f"    {{ {off}u, {ln}u, 0x{crc:08x}u }},\n")
        out.write("};\n\n")

    n = len(inputs)
    out.write(f"static constexpr size_t kCrcVectorCount = {n};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
